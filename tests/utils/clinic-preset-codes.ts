/** The test organization's id for a preset role (`rol_doctor`) — what a View-as preview stores. */
export function presetRoleId(role: Role): string {
  return `rol_${role}`;
}

/** Sign the store's member in holding a preset's codes — "as a Doctor" (`permissionsResolved`). */
export function holdPreset(role: Role): void {
  useOrganizationStore.getState().setPermissions([...PRESET_CODES[role]]);
}

/**
 * Run a View-as preview of a preset in this query client: the previewed role's id in the UI store
 * and its codes already read (never refetched), as Users › Roles & access starts one.
 */
export function previewPreset(queryClient: QueryClient, role: Role): void {
  const organizationId = useOrganizationStore.getState().organizationId;
  const key = orgQueryKeys.rolePermissions(organizationId, presetRoleId(role));
  queryClient.setQueryDefaults(key, { staleTime: Number.POSITIVE_INFINITY });
  queryClient.setQueryData(key, [...PRESET_CODES[role]]);
  useUIStore.setState({ previewRole: presetRoleId(role) });
}

/** me/context's `my_roles` for a member holding one preset — Today's focus and the Account menu. */
export function presetMyRoles(role: Role): MyRole[] {
  return [
    {
      id: presetRoleId(role),
      name: PRESET_ROLE_NAMES[role],
      tone: 'sky',
      isSystem: true,
    },
  ];
}
